import os
from datetime import datetime, timedelta

import psycopg
from flask import g
from psycopg.rows import dict_row


SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS customers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      qcc_id TEXT,
      company_name TEXT NOT NULL,
      credit_code TEXT NOT NULL UNIQUE,
      legal_person TEXT,
      company_status TEXT,
      address TEXT,
      registered_capital TEXT,
      established_date TEXT,
      risk_level TEXT NOT NULL DEFAULT 'low',
      has_new_risk SMALLINT NOT NULL DEFAULT 0,
      has_company_change SMALLINT NOT NULL DEFAULT 0,
      created_at TEXT NOT NULL,
      last_checked_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS risk_records (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id BIGINT NOT NULL REFERENCES customers(id),
      risk_type TEXT NOT NULL,
      risk_level TEXT NOT NULL,
      title TEXT NOT NULL,
      description TEXT,
      occurred_at TEXT NOT NULL,
      created_at TEXT NOT NULL,
      is_handled SMALLINT NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS company_changes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id BIGINT NOT NULL REFERENCES customers(id),
      field_name TEXT NOT NULL,
      old_value TEXT,
      new_value TEXT,
      changed_at TEXT NOT NULL,
      created_at TEXT NOT NULL
    )
    """,
)


def connect_db():
    return psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row)


def ensure_schema(db):
    for statement in SCHEMA_STATEMENTS:
        db.execute(statement)
    db.commit()


def get_db():
    if "db" not in g:
        g.db = connect_db()
    return g.db


def close_db(_error=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db():
    db = get_db()
    ensure_schema(db)
    if os.getenv("SEED_DEMO_DATA", "false").lower() == "true":
        count = db.execute("SELECT COUNT(*) AS count FROM customers").fetchone()["count"]
        if count == 0:
            seed_db(db)


def seed_db(db):
    from mock_data import CHANGES, COMPANIES
    from services.risk_engine import assess_company

    now = datetime.now()
    for index, company in enumerate(COMPANIES[:4]):
        checked = (now - timedelta(hours=index * 9 + 1)).isoformat(timespec="seconds")
        created = (now - timedelta(days=60 - index * 9)).isoformat(timespec="seconds")
        assessment = assess_company(company["id"])
        risk = {
            "level": assessment["level"],
            "items": [
                {
                    "type": item["name"],
                    "status": "danger" if item["level"] == "high" else "warning" if item["level"] == "medium" else "normal",
                    "detail": item["description"],
                }
                for item in assessment["major_risks"]
            ],
        }
        cur = db.execute(
            """
            INSERT INTO customers
              (qcc_id, company_name, credit_code, legal_person, company_status, address, registered_capital,
               established_date, risk_level, has_new_risk, has_company_change, created_at, last_checked_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id
            """,
            (
                company["id"], company["company_name"], company["credit_code"], company["legal_person"],
                company["company_status"], company["address"], company["registered_capital"], company["established_date"],
                risk["level"], 1 if index in (1, 2) else 0, 1 if CHANGES[company["id"]] else 0, created, checked,
            ),
        )
        customer_id = cur.fetchone()["id"]
        for ri, item in enumerate(item for item in risk["items"] if item["status"] != "normal"):
            occurred = (now - timedelta(days=index + ri, hours=2)).isoformat(timespec="seconds")
            level = "high" if item["status"] == "danger" else "medium"
            db.execute(
                """
                INSERT INTO risk_records
                  (customer_id, risk_type, risk_level, title, description, occurred_at, created_at, is_handled)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (customer_id, item["type"], level, f"新增{item['type']}记录", item["detail"], occurred, checked, 0 if index in (1, 2) else 1),
            )
        for change in CHANGES[company["id"]]:
            db.execute(
                """
                INSERT INTO company_changes
                  (customer_id, field_name, old_value, new_value, changed_at, created_at)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (customer_id, change["field_name"], change["old_value"], change["new_value"], change["changed_at"], checked),
            )
    db.commit()


def rows(rows_):
    return [dict(row) for row in rows_]
